#!/usr/bin/env python3
# oneVR: builds the lobby's icon font from Adwaita (and Papirus) symbolic icons
# Usage: onevr_icons.py [icon theme dir], writes assets/onevr-icons.otf and external/IconsOneVr.h

import sys
from pathlib import Path

from fontTools.fontBuilder import FontBuilder
from fontTools.pens.t2CharStringPen import T2CharStringPen
from fontTools.pens.transformPen import TransformPen
from fontTools.svgLib.path import SVGPath

ICONS = Path(sys.argv[1] if len(sys.argv) > 1 else "/usr/share/icons")
ADW = "Adwaita/symbolic/"
PAP = "Papirus/16x16/symbolic/"

# macro name: source svg, relative to the icon theme dir
GLYPHS = {
    "ADD": ADW + "actions/list-add-symbolic.svg",
    "AUTO": PAP + "actions/feather-zap-symbolic.svg",
    "BACKSPACE": ADW + "actions/edit-clear-symbolic.svg",
    "BATTERY_0": ADW + "status/battery-level-0-symbolic.svg",
    "BATTERY_20": ADW + "status/battery-level-20-symbolic.svg",
    "BATTERY_50": ADW + "status/battery-level-50-symbolic.svg",
    "BATTERY_80": ADW + "status/battery-level-80-symbolic.svg",
    "BATTERY_100": ADW + "status/battery-level-100-symbolic.svg",
    "BATTERY_CHARGED": ADW + "status/battery-level-100-charged-symbolic.svg",
    "CAPS_LOCK": PAP + "actions/keyboard-caps-lock-filled-symbolic.svg",
    "CHECK": ADW + "actions/object-select-symbolic.svg",
    "CLOSE": ADW + "ui/window-close-symbolic.svg",
    "COMPUTER": ADW + "devices/computer-symbolic.svg",
    "EDIT": ADW + "actions/document-edit-symbolic.svg",
    "GLOBE": PAP + "actions/globe-symbolic.svg",
    "LICENSE": ADW + "mimetypes/application-certificate-symbolic.svg",
    "MORE": ADW + "actions/view-more-symbolic.svg",
    "NETWORK_SERVER": ADW + "places/network-server-symbolic.svg",
    "NETWORK_WIRELESS": ADW + "devices/network-wireless-symbolic.svg",
    "PAN_DOWN": ADW + "ui/pan-down-symbolic.svg",
    "PLAY": ADW + "actions/media-playback-start-symbolic.svg",
    "POWER": ADW + "actions/system-shutdown-symbolic.svg",
    "REFRESH": ADW + "actions/view-refresh-symbolic.svg",
    "REMOVE": ADW + "actions/list-remove-symbolic.svg",
    "RESET": ADW + "actions/edit-undo-symbolic.svg",
    "SEARCH": ADW + "actions/system-search-symbolic.svg",
    "SHIFT": PAP + "actions/keyboard-shift-filled-symbolic.svg",
    "STOP": ADW + "actions/media-playback-stop-symbolic.svg",
    "TRASH": ADW + "places/user-trash-symbolic.svg",
    "USB": ADW + "devices/drive-harddisk-usb-symbolic.svg",
    "WARNING": ADW + "status/dialog-warning-symbolic.svg",
}

FIRST = 0xF0000  # supplementary private use area, clear of Font Awesome
UPM = 1000
SCALE = UPM / 16  # icons are drawn on a 16x16 grid
ASCENT = 875  # the icon spans -0.125 to 0.875 em, like Font Awesome

root = Path(__file__).resolve().parent.parent
names = [".notdef"] + [n.lower() for n in GLYPHS]
cmap, charstrings, metrics = {}, {}, {".notdef": (UPM, 0)}
charstrings[".notdef"] = T2CharStringPen(UPM, None).getCharString()
for i, (name, src) in enumerate(GLYPHS.items()):
    pen = T2CharStringPen(UPM, None)
    SVGPath(ICONS / src).draw(TransformPen(pen, (SCALE, 0, 0, -SCALE, 0, ASCENT)))
    charstrings[name.lower()] = pen.getCharString()
    cmap[FIRST + i] = name.lower()
    metrics[name.lower()] = (UPM, 0)

fb = FontBuilder(UPM, isTTF=False)
fb.setupGlyphOrder(names)
fb.setupCharacterMap(cmap)
fb.setupCFF("oneVRIcons-Regular", {"FullName": "oneVR Icons"}, charstrings, {})
fb.setupHorizontalMetrics(metrics)
fb.setupHorizontalHeader(ascent=ASCENT, descent=ASCENT - UPM)
fb.setupNameTable({"familyName": "oneVR Icons", "styleName": "Regular"})
fb.setupOS2(
    sTypoAscender=ASCENT, sTypoDescender=ASCENT - UPM, usWinAscent=ASCENT, usWinDescent=UPM - ASCENT
)
fb.setupPost()
fb.save(root / "assets/onevr-icons.otf")

with open(root / "external/IconsOneVr.h", "w") as f:
    f.write("// Generated by tools/onevr_icons.py, do not edit\n#pragma once\n\n")
    for i, (name, src) in enumerate(GLYPHS.items()):
        utf8 = "".join(f"\\x{b:02x}" for b in chr(FIRST + i).encode())
        f.write(f'#define ICON_ONEVR_{name} "{utf8}" // {src}\n')
